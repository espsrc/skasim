#!/usr/bin/env bash
# Runs inside the micromamba container started by docker/update-lock.sh.
# Solves environment.yml for linux-64 and writes the pinned lockfiles to /out.
set -euo pipefail

: "${CASA_VERSION:?}"

# The conda part of environment.yml (everything before the trailing pip block).
sed '/^ *- pip:/,$d' /repo/environment.yml > /tmp/env-conda.yml

micromamba create -y -q -n lock --channel-priority flexible -f /tmp/env-conda.yml
micromamba env export -n lock --explicit --md5 > /out/conda-linux-64.lock

# casatools must be the manylinux_2_28 wheel: it bundles OpenSSL 1.1, whereas
# the manylinux_2_34 wheel bundles a libssl.so.3 that cannot load against the
# conda-forge libcrypto.so.3 in this environment. Pin it by URL and hash.
casatools_ref="$(micromamba run -n lock python - <<PY
import json, time, urllib.request

url = "https://pypi.org/pypi/casatools/${CASA_VERSION}/json"
for attempt in range(5):
    try:
        files = json.load(urllib.request.urlopen(url, timeout=60))["urls"]
        break
    except OSError:
        if attempt == 4:
            raise
        time.sleep(10)
(wheel,) = [
    f for f in files
    if f["filename"].endswith("-cp312-cp312-manylinux_2_28_x86_64.whl")
]
print(f"casatools @ {wheel['url']}#sha256={wheel['digests']['sha256']}")
PY
)"

# skasim's runtime dependencies come from pyproject.toml; install it from a
# copy because /repo is mounted read-only. casatasks imports six but does not
# declare it.
mkdir -p /tmp/skasim
cp -r /repo/pyproject.toml /repo/README.md /repo/LICENSE /repo/src /tmp/skasim/
micromamba run -n lock python -m pip install -q --no-cache-dir --root-user-action=ignore \
    "${casatools_ref}" \
    "casatasks==${CASA_VERSION}" \
    "six" \
    "shadems>=0.5.4" \
    /tmp/skasim

# Everything pip installed (including any conda package it upgraded),
# excluding skasim itself, which the image installs from the selected ref.
CASATOOLS_REF="${casatools_ref}" micromamba run -n lock python - <<'PY' > /out/requirements-pip.lock
import importlib.metadata as md
import os

rows = []
for dist in md.distributions():
    installer = (dist.read_text("INSTALLER") or "").strip()
    name = dist.metadata["Name"]
    if installer != "pip" or name.lower() == "skasim":
        continue
    if name.lower() == "casatools":
        rows.append(os.environ["CASATOOLS_REF"])
    else:
        rows.append(f"{name}=={dist.version}")
print("# Generated by docker/update-lock.sh; installed with pip --no-deps.")
print("\n".join(sorted(set(rows), key=str.lower)))
PY

# Sanity check: the key runtime libraries load together in this solve
# (casatools needs measures data before it can be imported, so only its
# shared libraries are loaded here; the image build checks the full import).
micromamba run -n lock python -c "
import importlib.util, ctypes, glob, os
import numpy, astropy, karabo, oskar
lib = os.path.dirname(importlib.util.find_spec('casatools').origin)
ctypes.CDLL(glob.glob(os.path.join(lib, '__casac__', '_image*.so'))[0])
print('numpy', numpy.__version__, '| astropy', astropy.__version__, '| casatools libraries load')
"
